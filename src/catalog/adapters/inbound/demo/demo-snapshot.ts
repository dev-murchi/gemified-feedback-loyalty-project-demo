import type { DomainError } from '../../../../shared-kernel/domain-error.js';
import { BranchId, BrandId } from '../../../../shared-kernel/ids.js';
import type { Result } from '../../../../shared-kernel/result.js';
import { Branch, type QrIssuing } from '../../../domain/branch/branch.js';
import { GeoPoint } from '../../../domain/geo-point.js';
import type {
  DemoBranch,
  DemoCatalogDefinition,
} from './demo-catalog.definition.js';

export interface DemoBrandSnapshot {
  readonly id: string;
}

export interface DemoQrCodeSnapshot {
  readonly id: string;
  readonly token: string;
  readonly createdAt: string;
}

export interface DemoBranchSnapshot {
  readonly id: string;
  readonly qrCodes: readonly DemoQrCodeSnapshot[];
}

/**
 * Stored state of the demo catalog: QR codes issued once, by the domain, and printed. Keyed by the
 * definition keys, so ids and tokens never change across restarts or the PostgreSQL switch.
 */
export interface DemoCatalogSnapshot {
  readonly brands: Readonly<Record<string, DemoBrandSnapshot>>;
  readonly branches: Readonly<Record<string, DemoBranchSnapshot>>;
}

export const valueOrThrow = <T>(
  result: Result<T, DomainError>,
  what: string,
): T => {
  if (!result.ok)
    throw new Error(`Invalid demo data (${what}): ${result.error.code}`);
  return result.value;
};

const orphanKeys = (
  entries: Readonly<Record<string, unknown>>,
  defined: readonly { readonly key: string }[],
): string[] => {
  const keys = new Set(defined.map((item) => item.key));
  return Object.keys(entries).filter((key) => !keys.has(key));
};

/**
 * A snapshot entry without a definition is a printed QR code that nothing would load. Fail
 * instead of silently dropping it; remove the entry by hand if that is really intended.
 */
export function assertNoOrphans(
  definition: DemoCatalogDefinition,
  snapshot: DemoCatalogSnapshot,
): void {
  const orphans = [
    ...orphanKeys(snapshot.brands, definition.brands),
    ...orphanKeys(snapshot.branches, definition.branches),
  ];
  if (orphans.length > 0) {
    throw new Error(
      `Demo snapshot has entries without a definition: ${orphans.join(', ')}`,
    );
  }
}

/**
 * Keeps every existing entry unchanged and issues ids and QR codes only for definition keys the
 * snapshot does not have yet. QR codes come from `Branch.issueQrCode`, the only way to make a token.
 * Fails on snapshot entries that have no definition (see assertNoOrphans).
 */
export function completeDemoSnapshot(
  definition: DemoCatalogDefinition,
  existing: DemoCatalogSnapshot,
  issuing: QrIssuing,
): DemoCatalogSnapshot {
  assertNoOrphans(definition, existing);
  const brands = Object.fromEntries(
    definition.brands.map((brand) => [
      brand.key,
      existing.brands[brand.key] ?? { id: BrandId.generate(issuing.ids) },
    ]),
  );
  const branches = Object.fromEntries(
    definition.branches.map((branch) => [
      branch.key,
      existing.branches[branch.key] ?? issueDemoBranch(branch, brands, issuing),
    ]),
  );
  return { brands, branches };
}

function issueDemoBranch(
  definition: DemoBranch,
  brands: Readonly<Record<string, DemoBrandSnapshot>>,
  issuing: QrIssuing,
): DemoBranchSnapshot {
  const brand = brands[definition.brandKey];
  if (brand === undefined)
    throw new Error(`Unknown brand key "${definition.brandKey}"`);
  const branch = valueOrThrow(
    Branch.create({
      id: BranchId.generate(issuing.ids),
      brandId: brand.id as BrandId,
      name: definition.name,
      location: valueOrThrow(
        GeoPoint.create(definition.lat, definition.lng),
        definition.key,
      ),
    }),
    definition.key,
  );
  const code = branch.issueQrCode(issuing);
  return {
    id: branch.id,
    qrCodes: [
      {
        id: code.id,
        token: code.token,
        createdAt: code.createdAt.toISOString(),
      },
    ],
  };
}

/** The generated module's source; deterministic, in definition order. */
export function renderSnapshotModule(snapshot: DemoCatalogSnapshot): string {
  return [
    '// GENERATED by scripts/generate-demo-catalog.ts – do not edit by hand.',
    '// Demo data only: public in git, never loaded when NODE_ENV=production.',
    '',
    "import type { DemoCatalogSnapshot } from './demo-snapshot.js';",
    '',
    `export const demoCatalogSnapshot: DemoCatalogSnapshot = ${JSON.stringify(snapshot, null, 2)};`,
    '',
  ].join('\n');
}
